#!/usr/bin/env python3
"""Design the 48 kHz -> 16 kHz decimation filter and emit it for RTL and the golden model.

Kaiser-windowed sinc low-pass, 96 taps, cutoff 8 kHz (the 16 kHz output Nyquist),
beta 6. Coefficients are quantised to signed Q1.17 (18-bit, DSP48E2 B-port width)
and nudged so they sum to exactly 2**17, so the DC gain is exactly 1.

Why these numbers:
- 96 taps / beta 6 gives a transition band of about 7 to 9 kHz and roughly 60 dB
  stopband. Everything that aliases into 0-6.8 kHz after decimation comes from
  9.2-16 kHz and is therefore attenuated by the stopband (checked in test_coeffs.py).
- 96 taps x 2 channels = 192 MACs per output; at 16 kHz output that is 3.07 M MAC/s,
  one time-shared DSP running at 24.576 MHz (1536 audio-clock cycles per output).

Pure Python (no numpy) so the repo needs only cocotb + pytest.
Outputs:
  rtl/decim3_coeffs.vh  Verilog function decim3_coeff(k) (included by decim3_fir.v)
  sim/decim3_coeffs.py  COEFFS list used by the golden model
"""
import math
from pathlib import Path

TAPS = 96
FS_IN = 48000.0
FC = 8000.0
BETA = 6.0
FRAC = 17  # Q1.17


def i0(x):
    """Zeroth-order modified Bessel function of the first kind (series)."""
    total, term, k = 1.0, 1.0, 1
    while term > 1e-12 * total:
        term *= (x / (2.0 * k)) ** 2
        total += term
        k += 1
    return total


def design():
    m = (TAPS - 1) / 2.0
    wc = 2.0 * FC / FS_IN  # normalised cutoff (1.0 = Nyquist)
    h = []
    for n in range(TAPS):
        t = n - m
        sinc = 1.0 if t == 0 else math.sin(math.pi * wc * t) / (math.pi * wc * t)
        w = i0(BETA * math.sqrt(1.0 - (t / m) ** 2)) / i0(BETA)
        h.append(wc * sinc * w)
    s = sum(h)
    h = [v / s for v in h]
    q = [int(round(v * (1 << FRAC))) for v in h]
    # Force sum(q) == 2**FRAC by adjusting the symmetric centre pair (keeps linear phase).
    err = (1 << FRAC) - sum(q)
    c0, c1 = TAPS // 2 - 1, TAPS // 2
    q[c0] += err // 2
    q[c1] += err - err // 2
    assert sum(q) == 1 << FRAC
    assert all(-(1 << 17) <= v < (1 << 17) for v in q)
    return q


def main():
    root = Path(__file__).resolve().parent.parent
    q = design()
    lines = [
        "// Generated by scripts/gen_coeffs.py - do not edit.",
        f"// {TAPS}-tap Kaiser(beta={BETA}) low-pass, fc={FC:.0f} Hz at fs={FS_IN:.0f} Hz, signed Q1.17, sum = 2^17.",
        "function signed [17:0] decim3_coeff;",
        "    input [6:0] k;",
        "    begin",
        "        case (k)",
    ]
    for k, v in enumerate(q):
        lit = f"18'sd{v}" if v >= 0 else f"-18'sd{-v}"
        lines.append(f"            7'd{k}: decim3_coeff = {lit};")
    lines += ["            default: decim3_coeff = 18'sd0;", "        endcase", "    end", "endfunction", ""]
    (root / "rtl" / "decim3_coeffs.vh").write_text("\n".join(lines))
    (root / "sim" / "decim3_coeffs.py").write_text(
        "# Generated by scripts/gen_coeffs.py - do not edit.\n"
        f"TAPS = {TAPS}\nFRAC = {FRAC}\nFS_IN = {FS_IN}\nCOEFFS = {q!r}\n")
    print(f"wrote {TAPS} taps, sum={sum(q)}, max={max(q)}, min={min(q)}")


if __name__ == "__main__":
    main()
